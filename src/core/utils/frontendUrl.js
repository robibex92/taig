/**
 * Единый резолвер ссылок на сайт для исходящих сообщений (Telegram, MAX).
 *
 * Живёт в `core/utils`, а не в сервисе конкретного мессенджера, потому что
 * ссылка сайта нужна и поллеру MAX-бота, и рассылкам Telegram: держать два
 * экземпляра правила «как собрать адрес» означало бы, что они разъедутся
 * первыми же — на смене `FRONTEND_URL` или на переходе с http на https.
 */

/** База читается при вызове, а не при импорте: `dotenv.config()` в server.js выполняется уже после статических импортов. */
const frontendBase = () =>
  (process.env.FRONTEND_URL || "https://infojk.ru").replace(/\/+$/, "");

/**
 * Ссылка на страницу сайта в текстах уведомлений.
 *
 * Фронт намеренно на `HashRouter`: адрес без решётки на проде отдаёт 404, поэтому
 * форма `/#/ads/5` — единственная рабочая.
 */
export const frontendLink = (page) => `${frontendBase()}/#${page}`;

/**
 * Вход на сайт с query-параметром: `?tg_login=<код>` / `?max_login=<код>`.
 *
 * Не через `/#/…`: код читается до монтирования роутера (HashRouter положил бы
 * его внутрь хэша, и маршрутизация перестала бы совпадать с путём).
 */
export const frontendEntry = (query) => `${frontendBase()}/?${query}`;
